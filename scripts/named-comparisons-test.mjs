import assert from 'node:assert/strict';
import { renameNamedComparison, updateNamedComparison, listNamedComparisons, addNamedComparison, loadNamedComparison, removeNamedComparison } from '../preview/named-comparisons.mjs';
let raw = null;
let blocked = false;
globalThis.window = { localStorage: { getItem: () => raw, setItem: (_key, value) => { if (blocked) throw new Error(); raw = value; } } };
const models = [{ id: 'a', variants: [{ quantization: 'Q4_K_M' }] }];
const choices = Array(3).fill({ modelId: 'a', quantization: 'Q4_K_M' });
assert.deepEqual(listNamedComparisons(), []);
addNamedComparison(' Trabalho ', models, choices, 32);
assert.equal(loadNamedComparison('Trabalho', models).contextK, 32);
assert.throws(() => addNamedComparison('trabalho', models, choices, 8));
assert.equal(listNamedComparisons().length, 1);
assert.throws(() => addNamedComparison(' ', models, choices, 8));
assert.throws(() => addNamedComparison('x'.repeat(61), models, choices, 8));
blocked = true;
assert.throws(() => removeNamedComparison('Trabalho'));
assert.equal(listNamedComparisons().length, 1);
blocked = false;
for (let i = 1; i < 10; i++) addNamedComparison(`Teste ${i}`, models, choices, i);
assert.throws(() => addNamedComparison('Excedente', models, choices, 8));
assert.equal(listNamedComparisons().length, 10);
assert.throws(() => loadNamedComparison('Trabalho', []));
removeNamedComparison('Trabalho');
assert.equal(listNamedComparisons().length, 9);
assert.throws(() => loadNamedComparison('Trabalho', models));
const beforeRename = loadNamedComparison('Teste 1', models);
renameNamedComparison('Teste 1', 'Novo nome');
assert.deepEqual(loadNamedComparison('Novo nome', models), beforeRename);
assert.throws(() => renameNamedComparison('Novo nome', 'TESTE 2'));
assert.throws(() => renameNamedComparison('Ausente', 'Novo'));
assert.throws(() => renameNamedComparison('Novo nome', ' '));
updateNamedComparison('Novo nome', models, choices, 64);
assert.equal(loadNamedComparison('Novo nome', models).contextK, 64);
assert.equal(loadNamedComparison('Teste 2', models).contextK, 2);
blocked = true;
assert.throws(() => updateNamedComparison('Novo nome', models, choices, 8));
assert.throws(() => renameNamedComparison('Novo nome', 'Outro'));
assert.equal(loadNamedComparison('Novo nome', models).contextK, 64);
blocked = false;
assert.throws(() => updateNamedComparison('Novo nome', models, choices, 300));
assert.throws(() => updateNamedComparison('Ausente', models, choices, 8));
raw = '{broken';
assert.throws(() => addNamedComparison('Nova', models, choices, 8));
assert.equal(raw, '{broken');
delete globalThis.window;
console.log('PASS nomes: persistência, duplicatas, limites, falha de escrita, catálogo antigo e corrupção');
