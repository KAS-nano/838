import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

// Bundle only the existing pure TypeScript modules, without a separate preview engine.
const root = fileURLToPath(new URL('..', import.meta.url));
const entries = {
  'src/features/onboarding/types.ts': ['objectives', 'initialHardwareProfile'],
  'src/features/onboarding/validation.ts': ['validateHardware', 'validateGoals'],
  'src/data/seed-models.ts': ['seedModels'],
  'src/data/model-links.ts': ['modelExternalLinks', 'getModelExternalLinks'],
  'src/data/project-support.ts': ['projectSupport'],
  'src/data/support-payment.ts': ['supportPayment'],
  'src/data/seed-api-models.ts': ['seedApiModels'],
  'src/features/benchmarks/data.ts': ['seedBenchmarks'],
  'src/features/estimation/memory.ts': ['estimateMemory'],
  'src/features/benchmarks/estimator.ts': ['estimatePerformance'],
  'src/features/recommendation/engine.ts': ['calculateCompatibility'],
  'src/features/recommendation/hybrid.ts': ['recommendHybrid'],
  'src/features/profile/local-store.ts': ['demoHardwareProfile', 'isHardwareProfile', 'parseHardwareProfile'],
  'src/features/hardware/strength.ts': ['hardwareStrength', 'primaryBottleneck'],
  'src/features/hardware/upgrades.ts': ['suggestUpgrades', 'simulateUpgrade'],
  'src/features/systems/recommender.ts': ['recommendSystems'],
  'src/features/installation/recipes.ts': ['recipeFor', 'installationRecipes'],
  'src/features/comparison/engine.ts': ['DEFAULT_SELECTIONS', 'COMPARISON_METRICS', 'CONFIDENCE_LABELS', 'FIT_LABELS', 'ORIGIN_LABELS', 'createComparisonRows', 'filterCatalog', 'filterComparisonRows', 'sortComparisonRows', 'metricValue', 'metricScale', 'formatMetric'],
};
const modules = new Map();
function compile(id) {
  if (modules.has(id)) return;
  const source = fs.readFileSync(path.join(root, id), 'utf8');
  const compiled = ts.transpileModule(source, {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 },
  }).outputText;
  modules.set(id, '');
  const resolved = compiled.replace(/require\("([^"\n]+)"\)/g, (_match, specifier) => {
    if (!specifier.startsWith('.')) throw new Error(`Only local pure modules may enter the preview: ${specifier}`);
    const dependency = path.posix.normalize(path.posix.join(path.posix.dirname(id), `${specifier}.ts`));
    compile(dependency);
    return `load(${JSON.stringify(dependency)})`;
  });
  modules.set(id, resolved);
}
for (const id of Object.keys(entries)) compile(id);
const factories = [...modules].map(([id, code]) => `${JSON.stringify(id)}: (exports, load) => {\n${code}}`).join(',\n');
const exports = Object.entries(entries).flatMap(([id, names]) => names.map(name => `export const ${name} = load(${JSON.stringify(id)}).${name};`)).join('\n');
const output = `// Generated by scripts/export-preview-catalog.mjs from canonical TypeScript. Do not edit.\nconst factories = {\n${factories}\n};\nconst cache = Object.create(null);\nfunction load(id) {\n  if (!cache[id]) {\n    cache[id] = {};\n    factories[id](cache[id], load);\n  }\n  return cache[id];\n}\n${exports}\n`;
const target = path.join(root, 'preview/engine.mjs');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) throw new Error('Preview engine is stale. Run npm run preview:generate.');
} else fs.writeFileSync(target, output);
console.log(`Preview catalog and engine synchronized from ${modules.size} canonical modules.`);
